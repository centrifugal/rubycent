# frozen_string_literal: true

# Writes lib/cent/generated/ from proto/api.proto and proto/proxy.proto: the
# result and message types of every Centrifugo server API method, the methods
# of Client, Batch and Command taking each request's fields as keyword
# arguments, and the types of the proxy protocol.
#
#   ruby gen/generate.rb            # write
#   ruby gen/generate.rb --check    # fail when the committed files are stale
#
# The output is committed; `rake generate:check` runs the check in CI.

require "fileutils"
require_relative "proto"

ROOT = File.expand_path("..", __dir__)
OUT = File.join(ROOT, "lib/cent/generated")

# rpc calls server API extensions, which neither Centrifugo OSS nor PRO
# provides.
OMITTED_COMMANDS = %w[rpc].freeze

# Messages written by hand (BroadcastResult: a result per channel; Error: an
# exception), only used on the wire (the batch envelope), or wrappers which
# become optional scalars.
HANDWRITTEN = %w[Error BroadcastResult].freeze
WIRE_ONLY = %w[Command Reply BatchRequest BatchResponse].freeze
WRAPPERS = { "BoolValue" => :bool_value, "Int32Value" => :int32_value }.freeze

KINDS = {
  "string" => :str, "bool" => :bool, "bytes" => :json,
  "int32" => :int, "int64" => :int, "uint32" => :int, "uint64" => :int,
  "double" => :float, "float" => :float
}.freeze
DOC_TYPES = { str: "String", bool: "Boolean", int: "Integer", float: "Float", json: "Object" }.freeze
DEFAULTS = { str: '""', bool: "false", int: "0", float: "0.0" }.freeze

# Names the methods take besides a request's fields.
OWN_PARAMS = %w[timeout max_attempts attempt_timeout].freeze
RUBY_KEYWORDS = %w[
  BEGIN END alias and begin break case class def defined? do else elsif end ensure false for if in
  module next nil not or redo rescue retry return self super then true undef unless until when while yield
].freeze

HEADER = "# frozen_string_literal: true\n\n# Code generated by gen/generate.rb from proto/%s. DO NOT EDIT.\n\n"

Command = Struct.new(:method, :request, :result, :pro_only, keyword_init: true)

def commands(s)
  cmd = s.by_name["Command"] or abort "api.proto: Command message is required"
  reply = s.by_name["Reply"] or abort "api.proto: Reply message is required"
  results = reply.fields.to_h { [it.name, it.type] }
  cmd.fields.filter_map do |f|
    next if OMITTED_COMMANDS.include?(f.name)

    req = s.by_name[f.type]
    if req.nil? || !results.key?(f.name)
      abort "api.proto: Command.#{f.name} has no request message or no Reply.#{f.name}"
    end
    want = "#{f.name.split("_").map(&:capitalize).join}Request"
    abort "api.proto: Command.#{f.name} is #{f.type}, expected #{want}" unless f.type.casecmp?(want)
    Command.new(method: f.name, request: req, result: results[f.name],
                pro_only: f.doc.join(" ").include?("Centrifugo PRO only"))
  end
end

def skipped(s, cmds)
  names = HANDWRITTEN + WIRE_ONLY + WRAPPERS.keys
  names += s.methods.map(&:response) # the error-or-result envelopes
  %w[Command Reply].each do |c|
    s.by_name[c].fields.each { names << it.type if OMITTED_COMMANDS.include?(it.name) }
  end
  # Requests are not types: their methods take their fields.
  names += cmds.map { it.request.name }
  names.to_set
end

def kind(f) = KINDS[f.type] || WRAPPERS[f.type] || f.type

def shape(f)
  if f.map?
    :map
  else
    f.list? ? :list : :one
  end
end

# The YARD type of a field; +input+ for a method's parameter, which also takes
# a Hash for a message.
def doc_type(f, input: false)
  k = kind(f)
  base =
    case k
    when :bool_value then "Boolean"
    when :int32_value then "Integer"
    when Symbol then DOC_TYPES.fetch(k)
    else input ? "#{k}, Hash" : k
    end
  return "Hash{String => #{base}}" if f.map?
  return "Array<#{base}>" if f.list?
  return "#{base}, nil" if k.is_a?(String) || k == :bool_value || k == :int32_value || k == :json || input

  base
end

def default(f)
  return "[]" if f.list?
  return "{}" if f.map?

  DEFAULTS.fetch(kind(f), "nil")
end

def put_args(f, var, where)
  args = [%("#{f.name}"), var, where, kind(f).is_a?(Symbol) ? ":#{kind(f)}" : kind(f)]
  args << ":#{shape(f)}" unless shape(f) == :one
  args.join(", ")
end

def get_args(f)
  args = [%("#{f.name}"), "where", kind(f).is_a?(Symbol) ? ":#{kind(f)}" : kind(f)]
  args << ":#{shape(f)}" unless shape(f) == :one
  args.join(", ")
end

# A field's proto comment without the name it starts with, as Go's comments
# do: "skip_history skips..." -> "Skips...", "data is the payload" -> "The
# payload", "version, when > 0, is the version" -> "When > 0, the version".
def strip_name(f)
  lines = f.doc.dup
  return lines if lines.empty?

  name = Regexp.escape(f.name)
  first = lines[0]
  if (m = first.match(/\A`?#{name}`?\s+(?:(?:is|are)\s+(.*)|([a-z].*))\z/))
    lines[0] = cap(m[1] || m[2])
  elsif (m = first.match(/\A`?#{name}`?,\s*(.+?),\s+(?:(?:is|are)\s+)?(.*)\z/))
    lines[0] = "#{cap(m[1])}, #{m[2]}"
  end
  lines
end

def cap(s) = s[0].upcase + s[1..]

def comment(lines, indent)
  "#{lines.map { |l| l.empty? ? "#{indent}#" : "#{indent}# #{l}" }.join("\n")}\n"
end

# Proto comment lines, safe for YARD: a line starting with @ would be a tag.
def esc(lines) = lines.map { it.start_with?("@") ? "\\#{it}" : it }

def method_doc(c)
  doc = esc(c.request.doc)
  prefix = "#{c.request.name} "
  doc[0] = cap(doc[0].delete_prefix(prefix)) if !doc.empty? && doc[0].start_with?(prefix)
  doc = ["Calls the #{c.method} method of the Centrifugo server API."] if doc.empty?
  doc << "" << "Centrifugo PRO only." if c.pro_only && !doc.join(" ").include?("Centrifugo PRO only")
  doc
end

# @param tags for a field: the first line after the name, the rest indented.
def param_docs(m)
  m.fields.flat_map do |f|
    text = esc(strip_name(f))
    text = ["The #{f.name} field."] if text.empty?
    ["@param #{f.name} [#{doc_type(f, input: true)}] #{text[0]}", *text[1..].map { "  #{it}" }]
  end
end

def check_params(c)
  c.request.fields.each do |f|
    abort "api.proto: #{c.request.name}.#{f.name} is a Ruby keyword" if RUBY_KEYWORDS.include?(f.name)
    abort "api.proto: #{c.request.name}.#{f.name} would be the method's own #{f.name}:" if OWN_PARAMS.include?(f.name)
  end
end

# A method's signature: on one line when it fits, a parameter a line otherwise.
def signature(indent, name, params, block: nil)
  all = params + (block ? ["&#{block}"] : [])
  one = "#{indent}def #{name}(#{all.join(", ")})"
  return "#{indent}def #{name}" if all.empty?
  return one if one.size <= 100 && params.size <= 3

  "#{indent}def #{name}(\n#{all.map { "#{indent}  #{it}" }.join(",\n")}\n#{indent})"
end

def call_args(c) = c.request.fields.map(&:name)

def requests_call(c, indent)
  args = call_args(c)
  return "Requests.#{c.method}" if args.empty?

  one = "Requests.#{c.method}(#{args.join(", ")})"
  return one if args.size <= 4

  "Requests.#{c.method}(\n#{args.map { "#{indent}  #{it}" }.join(",\n")}\n#{indent})"
end

def emit_message(out, m, indent, protocol)
  doc = m.doc.empty? ? ["#{m.name} is the #{m.name} message of the Centrifugo #{protocol}."] : esc(m.doc)
  lines = doc.dup
  m.fields.each do |f|
    lines << "" if lines.last != "" && f == m.fields.first
    text = esc(strip_name(f))
    text = ["The #{f.name} field."] if text.empty?
    lines << "@!attribute [r] #{f.name}"
    lines << "  @return [#{doc_type(f)}] #{text[0]}"
    lines.concat(text[1..].map { "    #{it}" })
  end
  out << comment(lines, indent)
  members = m.fields.map { ":#{it.name}" }.join(", ")
  out << "#{indent}class #{m.name} < Data.define#{"(#{members})" unless members.empty?}\n"
  out << "#{indent}  include Message\n\n"
  unless m.fields.empty?
    params = m.fields.map { "#{it.name}: #{default(it)}" }
    sig = signature("#{indent}  ", "initialize", params)
    out << (sig.include?("\n") ? "#{sig}\n#{indent}    super\n#{indent}  end\n\n" : "#{sig} = super\n\n")
  end
  out << "#{indent}  # The message as Centrifugo reads it, fields at their zero value left out.\n"
  out << "#{indent}  #\n#{indent}  # @api private\n"
  out << "#{indent}  def to_wire(#{m.fields.empty? ? "_where" : "where"} = \"\")\n"
  if m.fields.empty?
    out << "#{indent}    {}\n"
  else
    out << "#{indent}    w = {}\n"
    m.fields.each { out << "#{indent}    Wire.put(w, #{put_args(it, it.name, "where")})\n" }
    out << "#{indent}    w\n"
  end
  out << "#{indent}  end\n\n"
  out << "#{indent}  # The message from the Hash JSON.parse gives for it.\n"
  out << "#{indent}  #\n#{indent}  # @api private\n"
  out << "#{indent}  def self.from_wire(v, where = #{m.name.inspect})\n"
  if m.fields.empty?
    out << "#{indent}    Wire.obj(v, where)\n#{indent}    new\n"
  else
    out << "#{indent}    d = Wire.obj(v, where)\n#{indent}    new(\n"
    m.fields.each { out << "#{indent}      #{it.name}: Wire.get(d, #{get_args(it)}),\n" }
    out[-2..] = "\n"
    out << "#{indent}    )\n"
  end
  out << "#{indent}  end\n#{indent}end\n"
end

def emit_requests(out, cmds)
  out << "  # The JSON of each API method's request, from its fields, as the methods of\n"
  out << "  # Client, Batch and Command take them.\n  #\n  # @api private\n"
  out << "  module Requests\n    module_function\n"
  cmds.each do |c|
    out << "\n"
    params = call_args(c)
    out << "#{signature("    ", c.method, params)}\n"
    if c.request.fields.empty?
      out << "      {}\n"
    else
      out << "      w = {}\n"
      c.request.fields.each { out << "      Wire.put(w, #{put_args(it, it.name, '""')})\n" }
      out << "      w\n"
    end
    out << "    end\n"
  end
  out << "  end\n"
end

TIMEOUT_DOC = "@param timeout [Numeric, nil] Seconds bounding the call: request_timeout when nil."

BROADCAST_DOC = <<~DOC.lines(chomp: true)
  Channels succeed or fail on their own. It returns when every channel got the
  publication. When Centrifugo carried the broadcast out and one or more
  channels failed - up to all of them - it raises BroadcastFailedChannelsError,
  whose result holds every channel's outcome. Any other error means it failed
  as a whole: no channel got a reply. After a timeout or a network error
  Centrifugo may still have published it.

  To go on despite some failed channels:

    begin
      client.broadcast(channels:, data:)
    rescue Cent::BroadcastFailedChannelsError => e
      logger.warn("broadcast failed in \#{e.result.failed.map(&:channel)}")
    end

  Retry it with broadcast_with_retry, which sends again only the channels which
  may still succeed, with one idempotency_key.
DOC

BROADCAST_RETRY_DOC = <<~DOC.lines(chomp: true)
  Broadcasts as broadcast does, and retries the channels which failed for a
  temporary reason - see Cent.retryable? - up to max_attempts (2 by default:
  one retry).

  - Only the channels which may still succeed are sent again; when only
    channels which failed for good are left, it stops.
  - Every attempt carries the same idempotency_key - made for the call when
    none is given - so that a channel which got the publication in an earlier
    attempt does not get it again. The memory, Redis and PostgreSQL brokers
    keep keys; the NATS broker ignores them, and a retry may publish again.
  - The result holds every channel's last outcome, and the key: retrying later
    with it publishes only into the channels which did not get it.

  timeout, when set, bounds the whole call, waits included; attempt_timeout -
  request_timeout by default - bounds each attempt.

  The block, when given, is called after an attempt which failed in a way a
  retry may fix, except the last, with a BroadcastAttempt. It returns the
  seconds to wait before the next attempt, or nil for the default wait -
  Cent.exponential_backoff(0.1, 5.0) of the attempt - and may log or count
  meanwhile. To stop, it raises: its exception propagates, its cause the
  attempt's error. The wait never outlasts the call's timeout.

    client.broadcast_with_retry(channels:, data:, max_attempts: 5) do |attempt|
      logger.info("attempt \#{attempt.attempt}: \#{attempt.retry.size} channels to retry")
      nil
    end

  It raises as broadcast does.
DOC

def emit_methods(out, name, intro, cmds)
  out << comment(intro, "  ")
  out << "  module #{name}\n"
  first = true
  cmds.each do |c|
    check_params(c)
    out << "\n" unless first
    first = false
    yield c
  end
  out << "  end\n"
end

def method_body(out, doc, sig, body)
  out << comment(doc, "    ")
  out << "#{sig}\n"
  out << body.map { "      #{it}\n" }.join
  out << "    end\n"
end

def emit_client_methods(out, cmds)
  intro = ["The server API methods of Client, one per method of api.proto.", "", "@api private"]
  emit_methods(out, "ClientMethods", intro, cmds) do |c|
    params = c.request.fields.map { "#{it.name}: nil" }
    call = requests_call(c, "      ")
    if c.method == "broadcast"
      doc = [*method_doc(c), "", *BROADCAST_DOC, "", *param_docs(c.request), TIMEOUT_DOC,
             "@return [BroadcastResult]", "@raise [Error]"]
      method_body(out, doc, signature("    ", c.method, [*params, "timeout: nil"]),
                  ["send_broadcast(timeout) do", "  #{call.gsub("\n", "\n  ")}", "end"])
      out << "\n"
      doc = [*BROADCAST_RETRY_DOC, "", *param_docs(c.request),
             "@param max_attempts [Integer] Attempts at most, the first included.",
             "@param attempt_timeout [Numeric, nil] Seconds bounding each attempt: request_timeout when nil.",
             "@param timeout [Numeric, nil] Seconds bounding the whole call, waits included: no",
             "  bound but each attempt's when nil.",
             "@yieldparam attempt [BroadcastAttempt] a failed attempt which will be retried",
             "@yieldreturn [Numeric, nil] seconds to wait before the next attempt, nil for the default",
             "@return [BroadcastResult]", "@raise [Error]"]
      own = ["max_attempts: 2", "attempt_timeout: nil", "timeout: nil"]
      method_body(out, doc, signature("    ", "broadcast_with_retry", [*params, *own], block: "on_attempt_error"),
                  ["retry_broadcast(max_attempts, attempt_timeout, timeout, on_attempt_error) do",
                   "  #{call.gsub("\n", "\n  ")}", "end"])
    else
      doc = [*method_doc(c), "", *param_docs(c.request), TIMEOUT_DOC, "@return [#{c.result}]", "@raise [Error]"]
      method_body(out, doc, signature("    ", c.method, [*params, "timeout: nil"]),
                  ["invoke(#{c.method.inspect}, #{c.result}, timeout) do", "  #{call.gsub("\n", "\n  ")}", "end"])
    end
  end
end

def emit_batch_methods(out, cmds)
  intro = ["The commands of Batch, one per method of api.proto.", "", "@api private"]
  emit_methods(out, "BatchMethods", intro, cmds) do |c|
    result = c.method == "broadcast" ? "BroadcastResult" : c.result
    sent = "is sent."
    sent = "is sent, and raises BroadcastFailedChannelsError when any channel failed." if c.method == "broadcast"
    doc = [*method_doc(c), "", "Adds the command to the batch: its Pending holds the result once the batch",
           sent, "", *param_docs(c.request), "@return [Pending<#{result}>]"]
    params = c.request.fields.map { "#{it.name}: nil" }
    call = requests_call(c, "      ")
    add = c.method == "broadcast" ? "add_broadcast do" : "add(#{c.method.inspect}, #{result}) do"
    method_body(out, doc, signature("    ", c.method, params), [add, "  #{call.gsub("\n", "\n  ")}", "end"])
  end
end

def emit_command_methods(out, cmds)
  intro = ["The commands of Command, one per method of api.proto.", "", "@api private"]
  emit_methods(out, "CommandMethods", intro, cmds) do |c|
    doc = [*method_doc(c), "", "The command making the call, checked as a Client checks it.", "",
           *param_docs(c.request), "@return [Command]", "@raise [InvalidRequestError]"]
    params = c.request.fields.map { "#{it.name}: nil" }
    call = requests_call(c, "      ")
    method_body(out, doc, signature("    ", c.method, params),
                ["build(#{c.method.inspect}) do", "  #{call.gsub("\n", "\n  ")}", "end"])
  end
end

# The proxy messages the methods which are not streaming use, directly or
# through their fields - but the envelopes, which the handlers build, Error and
# Disconnect, which are exceptions, and the wrappers.
def proxy_messages(s)
  used = Set.new
  visit = lambda do |name|
    m = s.by_name[name]
    next if m.nil? || used.include?(name)

    used << name
    m.fields.each { visit.call(it.type) }
  end
  envelopes = Set.new
  s.methods.each do |rpc|
    next if rpc.streaming

    visit.call(rpc.request)
    visit.call(rpc.response)
    envelopes << rpc.response
  end
  skip = envelopes + %w[Error Disconnect] + WRAPPERS.keys
  s.messages.select { used.include?(it.name) && !skip.include?(it.name) }
end

def generate
  api = Proto.parse(File.read(File.join(ROOT, "proto/api.proto")), "api.proto")
  cmds = commands(api)
  skip = skipped(api, cmds)
  # A request which is also another message's field would need a type.
  api.messages.reject { WIRE_ONLY.include?(it.name) }.each do |m|
    m.fields.each do |f|
      if cmds.any? { it.request.name == f.type }
        abort "api.proto: #{m.name}.#{f.name} is a request, #{f.type}: generate a type for it"
      end
    end
  end

  types = +format(HEADER, "api.proto")
  types << "module Cent\n"
  api.messages.reject { skip.include?(it.name) }.each_with_index do |m, i|
    types << "\n" unless i.zero?
    emit_message(types, m, "  ", "server API")
  end
  types << "end\n"

  methods = +format(HEADER, "api.proto")
  methods << "module Cent\n"
  methods << "  # Every API method, batch included, and whether only Centrifugo PRO has it.\n"
  methods << "  #\n  # @api private\n  API_METHODS = {\n    \"batch\" => false,\n"
  methods << cmds.map { "    #{it.method.inspect} => #{it.pro_only}" }.join(",\n")
  methods << "\n  }.freeze\n\n"
  emit_requests(methods, cmds)
  methods << "\n"
  emit_client_methods(methods, cmds)
  methods << "\n"
  emit_batch_methods(methods, cmds)
  methods << "\n"
  emit_command_methods(methods, cmds)
  methods << "end\n"

  proxy = Proto.parse(File.read(File.join(ROOT, "proto/proxy.proto")), "proxy.proto")
  proxy_types = +format(HEADER, "proxy.proto")
  proxy_types << "module Cent\n  module Proxy\n"
  proxy_messages(proxy).each_with_index do |m, i|
    proxy_types << "\n" unless i.zero?
    emit_message(proxy_types, m, "    ", "proxy protocol")
  end
  proxy_types << "  end\nend\n"

  { "types.rb" => types, "methods.rb" => methods, "proxy_types.rb" => proxy_types }
end

files = generate
if ARGV.include?("--check")
  stale = files.reject { |name, text| File.exist?(File.join(OUT, name)) && File.read(File.join(OUT, name)) == text }
  unless stale.empty?
    warn "stale generated code: #{stale.keys.join(", ")}: run `rake generate`"
    exit 1
  end
else
  FileUtils.mkdir_p(OUT)
  files.each { |name, text| File.write(File.join(OUT, name), text) }
end
